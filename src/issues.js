'use strict';
const { fingerprint, sevRank } = require('./util');

const LABEL_META = {
  'site-sweep': ['5319e7', 'Filed by site-sweep'],
  'severity:high': ['b60205', 'High severity site-sweep finding'],
  'severity:medium': ['fbca04', 'Medium severity site-sweep finding'],
  'severity:low': ['0e8a16', 'Low severity site-sweep finding'],
};

const markerFor = (fp) => `<!-- site-sweep-fp:${fp} -->`;

function groupFindings(findings, { startUrl, command }) {
  const origin = new URL(startUrl).origin;
  const map = new Map();
  for (const f of findings) {
    const k = `${f.type}|${f.severity}`;
    if (!map.has(k)) map.set(k, []);
    map.get(k).push(f);
  }
  const groups = [...map.values()].map((fs) => {
    const { type, severity } = fs[0];
    const fp = fingerprint('group', type, severity, origin);
    const pages = [...new Set(fs.map((f) => f.page))];
    const lines = [];
    for (const p of pages.slice(0, 25)) {
      const first = fs.find((f) => f.page === p);
      const n = fs.filter((f) => f.page === p).length;
      lines.push(`- ${p} - ${first.message}${first.selector ? ` (\`${first.selector.replace(/`/g, "'")}\`)` : ''}${n > 1 ? ` (+${n - 1} more on this page)` : ''}`);
    }
    if (pages.length > 25) lines.push(`- ... and ${pages.length - 25} more pages`);
    const body = [
      markerFor(fp),
      `**Type:** \`${type}\`  `,
      `**Severity:** ${severity}  `,
      `**Findings:** ${fs.length} on ${pages.length} page(s) of ${origin}`,
      '',
      '### Affected pages',
      ...lines,
      '',
      '### How to reproduce',
      '1. Install site-sweep and its dependencies (`npm install`).',
      `2. Run: \`${command}\``,
      `3. Look for \`${type}\` findings (${severity}) in \`site-sweep-out/report.md\`.`,
      '',
      '_This issue was generated by site-sweep. Re-running the sweep will not file it again while it is open._',
    ].join('\n');
    return {
      fingerprint: fp,
      marker: markerFor(fp),
      type,
      severity,
      count: fs.length,
      title: `[site-sweep] ${severity} ${type}: ${fs.length} finding(s) on ${pages.length} page(s)`,
      labels: ['site-sweep', `severity:${severity}`],
      body,
    };
  });
  groups.sort((a, b) => sevRank(b.severity) - sevRank(a.severity) || b.count - a.count || a.type.localeCompare(b.type));
  return groups;
}

// Dry run (yes=false) never touches gh at all.
function processIssues(findings, { repo, yes, maxIssues, gh, startUrl, command, log }) {
  if (!/^[\w.-]+\/[\w.-]+$/.test(repo)) throw new Error(`--create-issues expects OWNER/REPO, got "${repo}"`);
  const groups = groupFindings(findings, { startUrl, command });
  const result = { created: [], skippedDuplicates: [], wouldCreate: [], capped: 0 };
  let labels = null;
  const ensureLabels = (needed) => {
    if (labels === null) labels = new Set(gh.listLabels(repo));
    for (const l of needed) {
      if (!labels.has(l)) {
        const [color, desc] = LABEL_META[l] || ['ededed', 'site-sweep'];
        gh.createLabel(repo, l, color, desc);
        labels.add(l);
      }
    }
  };
  let used = 0;
  for (const g of groups) {
    if (used >= maxIssues) {
      result.capped++;
      continue;
    }
    if (!yes) {
      used++;
      result.wouldCreate.push(g);
      log(`--- DRY RUN issue ${used} (nothing created) ---\nTitle: ${g.title}\nLabels: ${g.labels.join(', ')}\nBody:\n${g.body}\n`);
      continue;
    }
    const dup = gh.findOpenIssueWithMarker(repo, g.marker, g.fingerprint);
    if (dup) {
      result.skippedDuplicates.push({ group: g, number: dup.number });
      log(`skip duplicate (open issue #${dup.number}): ${g.title}`);
      continue;
    }
    ensureLabels(g.labels);
    const url = gh.createIssue(repo, g);
    used++;
    result.created.push({ group: g, url });
    log(`created: ${url || g.title}`);
  }
  return result;
}

module.exports = { groupFindings, processIssues, markerFor };
